"""Manifest of the code-and-data release promised in the paper's availability statement (review issue 5).

Lists every git-tracked file under the release roots (run logs excluded), with category, size and SHA-256.
    python3 paper/release/build_release_manifest.py            # writes RELEASE_MANIFEST.csv and README_release.md
    python3 paper/release/build_release_manifest.py --zip OUT  # also writes the upload archive OUT (zip, paths as in the repo)
The DOI is minted by Zenodo on upload; it then replaces the placeholder in sec_conclusion.tex, the cover letter and the supplement.
"""
import argparse, csv, hashlib, os, subprocess, zipfile
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
ROOTS = ['Optimized/v17', 'Optimized/v17x', 'Optimized/case_registry.csv', 'paper/analysis', 'paper/proposals', 'paper/ledger', 'paper/supplement/files']
def category(p):
    if p == 'Optimized/case_registry.csv' or p.startswith('paper/ledger/'): return 'case registry and multiplicity ledger'
    if p.startswith('paper/proposals/'): return 'pre-registrations, amendments and freeze files'
    if p.startswith('paper/analysis/'): return 'analysis scripts and their outputs'
    if p.startswith('paper/supplement/files/'): return 'supplementary files (S1-S6)'
    if p.startswith('Optimized/v17/release/'): return 'v17 release bundle'
    if '/Dataset/' in p and ('/ckpt/' in p or p.endswith(('.joblib', '.onnx'))): return 'trained policies, calibrated tables and models'
    if '/Dataset/' in p or '/paper/' in p: return 'per-seed and per-trace results, result tables'
    return 'simulator, trace and CRN generators, stage code'
files = subprocess.run(['git', '-C', ROOT, 'ls-files', '--', *ROOTS], capture_output=True, text=True, check=True).stdout.splitlines()
files = [f for f in files if '/logs/' not in f and os.path.exists(os.path.join(ROOT, f))]
rows = []
for f in sorted(files):
    b = open(os.path.join(ROOT, f), 'rb').read()
    rows.append(dict(path=f, category=category(f), bytes=len(b), sha256=hashlib.sha256(b).hexdigest()))
with open(os.path.join(HERE, 'RELEASE_MANIFEST.csv'), 'w', newline='', encoding='utf-8') as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator='\n'); w.writeheader(); w.writerows(rows)
cats = {}
for r in rows: c = cats.setdefault(r['category'], [0, 0]); c[0] += 1; c[1] += r['bytes']
commit = subprocess.run(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
lines = ['# Code and data release (Zenodo)', '', f'Generated by `paper/release/build_release_manifest.py` at repository commit {commit}.', '',
         f'**{len(rows)} files, {sum(r["bytes"] for r in rows)/1e6:.1f} MB.** Every file is listed with its SHA-256 in `RELEASE_MANIFEST.csv`.', '',
         '| Category | Files | MB |', '|---|---|---|']
lines += [f'| {k} | {v[0]} | {v[1]/1e6:.1f} |' for k, v in sorted(cats.items(), key=lambda x: -x[1][1])]
lines += ['', '## Upload steps', '1. `python3 paper/release/build_release_manifest.py --zip release.zip` from the repository root.',
          '2. Create a Zenodo upload with `release.zip`, `RELEASE_MANIFEST.csv` and the supplement PDF; licence and creators as agreed by the authors.',
          '3. Reserve or publish the DOI and replace the placeholder in `paper/manuscript/sec_conclusion.tex` (availability statement), the cover letter and the supplement title page.',
          '4. Verify after download: every SHA-256 in `RELEASE_MANIFEST.csv` must match.', '']
open(os.path.join(HERE, 'README_release.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
ap = argparse.ArgumentParser(); ap.add_argument('--zip'); a = ap.parse_args()
if a.zip:
    with zipfile.ZipFile(a.zip, 'w', zipfile.ZIP_DEFLATED) as z:
        for r in rows: z.write(os.path.join(ROOT, r['path']), r['path'])
print('\n'.join(lines[:4 + len(cats) + 4]))
