"""Generate LaTeX tables (paper/manuscript/gen/*.tex) directly from result files.
Every cell is read from the file named in the table's source comment; nothing is typed.
Run from paper/manuscript:  python3 build_tables.py
"""
import csv, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen'); os.makedirs(OUT, exist_ok=True)
P = lambda *a: os.path.join(ROOT, *a)
rows_of = lambda p: list(csv.DictReader(open(p, newline='', encoding='utf-8')))
MINUS = r'\ensuremath{-}'
def n(x, d=2, sign=False):
    x = float(x); s = f'{x:.{d}f}'
    if s.startswith('-'): return MINUS + s[1:]
    return ('+' + s) if sign and x != 0 else s
def sci(x):
    m, e = f'{float(x):.1e}'.split('e'); return rf'${m}\times10^{{{int(e)}}}$'
def write(name, src, body):
    open(os.path.join(OUT, name), 'w', encoding='utf-8').write(f'% generated by build_tables.py from {src} -- do not edit\n' + body)

# ---- G6 family (trace level) with seed-level columns where computed
tc = rows_of(P('Optimized/v17x/Dataset/table_cal500.csv'))
sd = {r['comparator']: r for r in rows_of(P('paper/analysis/out/g6_seed_stats.csv'))}
ev = {r['comparator']: r['cmp_mean'] for r in rows_of(P('paper/analysis/out/g6_seed_stats.csv'))}
L = []
for r in tc:
    c = r['comparator']; s = sd.get(c)
    name = {'Context-joint-500': r'\textbf{Combined table}', 'Context-500': 'Context table (re-cal.)', 'Fixed-500': 'Fixed (re-cal.)',
            'FixedPU-500': 'FixedPU (re-cal., class oracle)', 'OLLA-tuned-500': 'OLLA (re-tuned)'}.get(c, c)
    seeds = f"{s['seeds_above']}" if s else '--'
    hier = f"[{n(s['hier_boot_ci95_lo'], 2, True)}, {n(s['hier_boot_ci95_hi'], 2, True)}]" if s else '--'
    rob = ('yes' if s['seed_robust_R2'] == '1' else r'\textbf{no}') if s else '--'
    L.append(f"{name} & {n(r['margin_pct'], 2, True)} & [{n(r['ci90_lo'], 2, True)}, {n(r['ci90_hi'], 2, True)}] & {sci(r['holm_p'])} & "
             f"{'yes' if r['beats'] == '1' else 'no'} & {seeds} & {hier} & {rob}\\\\")
write('tab_g6.tex', 'Optimized/v17x/Dataset/table_cal500.csv; paper/analysis/out/g6_seed_stats.csv', '\n'.join(L) + '\n')

# ---- combined table (36 cells) with decision counts; sparse cells marked
cells = rows_of(P('Optimized/v17x/Dataset/ctxj_cells.csv'))
tab = {}
for m in re.finditer(r'cell\((\d),(\d),(\d),(\d)\) = (-?\d+)', open(P('Optimized/v17x/Dataset/cal500_tables.txt'), encoding='utf-8').read()):
    tab[tuple(int(x) for x in m.groups()[:4])] = int(m.group(5))
L = []
for b in (1, 2, 3):
    for d in (1, 2):
        row = [f'{b}', f'{d}']
        for v in (1, 2, 3):
            for u in (0, 1):
                c = next(x for x in cells if (int(x['slack_bin']), int(x['delay_class']), int(x['speed_class']), int(x['busy_bin'])) == (b, d, v, u))
                val = n(tab[(b, d, v, u)], 0)
                row.append((val + r'$^\ast$') if c['is_sparse'] == '1' else val)
        L.append(' & '.join(row) + r'\\')
write('tab_ctxj.tex', 'Optimized/v17x/Dataset/cal500_tables.txt; ctxj_cells.csv', '\n'.join(L) + '\n')

# ---- M2-M4 comparator tables (Appendix B)
TC = rows_of(P('Optimized/v17/paper/table_core.csv'))
NAME = {'Baseline': 'Baseline', 'OLLA': 'OLLA', 'OLLA (tuned target)': 'OLLA (tuned target)', 'Multi-OLLA': 'Multi-OLLA', 'Fixed': 'Fixed',
        'FixedPU (Oracle)': 'FixedPU (class oracle)', 'Context table': 'Context table', 'Bandit (global)': 'Bandit (global)', 'Bandit (delay class)': 'Bandit (delay class)'}
for case, fn in [('M2_dl_rtt0', 'tab_m2.tex'), ('M3_gp_rtt8', 'tab_m3.tex'), ('M4_gp_rtt0', 'tab_m4.tex')]:
    L = []
    for r in TC:
        if r['case_tag'] == case and r['scheme'] == 'Deep A2C v17':
            L.append(f"{NAME[r['comparator']]} & {n(r['pct_margin'], 2, True)} & [{n(r['ci90_lo'], 2, True)}, {n(r['ci90_hi'], 2, True)}] & {sci(r['holm_p'])} & {'yes' if r['beats'] == '1' else 'no'}\\\\")
    write(fn, 'Optimized/v17/paper/table_core.csv', '\n'.join(L) + '\n')

# ---- registry summary by version (Appendix D)
reg = rows_of(P('Optimized/case_registry.csv'))
vers = sorted({r['version'] for r in reg}, key=lambda v: int(v.lstrip('v')))
L = []
for v in vers:
    rr = [r for r in reg if r['version'] == v]; ids = {r['case_id'] for r in rr}
    sup = len({r['case_id'] for r in rr if r['status'].startswith('superseded')})
    win = len({r['case_id'] for r in rr if r['win'] == '1' and r['status'] == 'valid'})
    L.append(f"{v} & {len(ids)} & {len(rr)} & {win} & {sup}\\\\")
L.append(r'\midrule')
ids = {r['case_id'] for r in reg}
L.append(f"all & {len(ids)} & {len(reg)} & {len({r['case_id'] for r in reg if r['win'] == '1' and r['status'] == 'valid'})} & {len({r['case_id'] for r in reg if r['status'].startswith('superseded')})}\\\\")
write('tab_registry.tex', 'Optimized/case_registry.csv', '\n'.join(L) + '\n')
print('tables written to', OUT)
