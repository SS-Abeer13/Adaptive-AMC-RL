"""pending_values.csv + pending_status.csv -> pending_values.tex + pending_status.tex.
Validates every (item, key) against pending_manifest.csv and formats each value by the
manifest's format column.  Run from paper/manuscript:  python3 -I build_pending.py
"""
import csv, sys, re

def tex_escape(s):
    s = s.replace('\\', r'\textbackslash{}')
    for a, b in [('%', r'\%'), ('&', r'\&'), ('#', r'\#'), ('_', r'\_'), ('$', r'\$'), ('{', r'\{'), ('}', r'\}')]:
        s = s.replace(a, b)
    return s

def fmt(value, f):
    v = value.strip()
    if f.endswith('f') and f.startswith('0.'):
        return format(float(v), f[1:])
    if f == 'integer':
        return str(int(float(v)))
    if f == 'sci':
        m, e = format(float(v), '.1e').split('e')
        return f'${m}\\times10^{{{int(e)}}}$'
    return tex_escape(v)          # choice, text

def main():
    man = {(r['item'], r['key']): r for r in csv.DictReader(open('pending_manifest.csv', newline=''))}
    items = sorted({i for i, _ in man})
    errs = []
    out = ['% generated by build_pending.py -- do not edit']
    have = {}
    for r in csv.DictReader(open('pending_values.csv', newline='')):
        k = (r['item'], r['key'])
        if k not in man:
            errs.append(f'unknown (item,key) in pending_values.csv: {k}'); continue
        try:
            val = fmt(r['value'], man[k]['format'])
        except Exception as e:
            errs.append(f'cannot format {k} value "{r["value"]}" as {man[k]["format"]}: {e}'); continue
        if man[k]['format'] == 'choice' and ' | ' in man[k]['description'] and False:
            pass
        have[k] = val
        out.append(f'\\pendingdef{{{k[0]}}}{{{k[1]}}}{{{val}}}')
    open('pending_values.tex', 'w').write('\n'.join(out) + '\n')
    st = ['% generated by build_pending.py -- do not edit']
    for r in csv.DictReader(open('pending_status.csv', newline='')):
        if r['item'] not in items: errs.append(f'unknown item in pending_status.csv: {r["item"]}'); continue
        if r['status'] not in ('run', 'not_run', 'pending'): errs.append(f'bad status {r}'); continue
        st.append(f'\\pendingstatus{{{r["item"]}}}{{{r["status"]}}}')
        if r['status'] == 'run':
            missing = [k for (i, k) in man if i == r['item'] and (i, k) not in have]
            if missing: print(f'note: item {r["item"]} is "run" but has no value for: {", ".join(missing)}')
    open('pending_status.tex', 'w').write('\n'.join(st) + '\n')
    print(f'{len(have)} values written; {len(items)} items')
    if errs:
        print('ERRORS:'); [print('  ', e) for e in errs]; sys.exit(1)

if __name__ == '__main__':
    main()
